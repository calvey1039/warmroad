// Fallback: estimate based on population for destinations not in the map
function estimateByPopulation(population?: number): LodgingEstimate {
  if (!population || population < 10000) return { low: 70, high: 160 };
  if (population < 100000) return { low: 80, high: 180 };
  if (population < 300000) return { low: 85, high: 190 };
  if (population < 500000) return { low: 95, high: 210 };
  return { low: 100, high: 220 };
}

export function getLodgingEstimate(destinationId: string, population?: number): string {
  const estimate = lodgingByDestination[destinationId] ?? estimateByPopulation(population);
  return `$${estimate.low}-${estimate.high}/night`;
}
